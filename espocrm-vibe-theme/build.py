#!/usr/bin/env python3
"""Builds the Vibe theme stylesheets from src/ and packs the EspoCRM extension zip.

Usage: python3 build.py
Output:
  extension/files/client/custom/modules/vibe-theme/css/*.css
  dist/vibe-theme-<version>.zip  (install via Administration > Extensions)
"""

import json
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / 'src'
EXT = ROOT / 'extension'
CSS_OUT = EXT / 'files/client/custom/modules/vibe-theme/css'
DIST = ROOT / 'dist'

# Path from client/custom/modules/vibe-theme/css/ to client/css/espo/.
ESPO_CSS = '../../../../css/espo/'

BUNDLES = {
    'vibe.css': ('espo.css', 'tokens-light.css', 'Vibe', True),
    'vibe-dark.css': ('dark.css', 'tokens-dark.css', 'VibeDark', True),
    'vibe-iframe.css': ('espo-iframe.css', 'tokens-light.css', None, False),
    'vibe-dark-iframe.css': ('dark-iframe.css', 'tokens-dark.css', None, False),
}

IFRAME_RULES = """
body {
    font-family: var(--font-family);
    color: var(--vibe-text);
}
"""


def read(name: str) -> str:
    return (SRC / name).read_text(encoding='utf-8').strip() + '\n'


def build_css() -> None:
    CSS_OUT.mkdir(parents=True, exist_ok=True)

    for out_name, (base, tokens, theme_name, with_components) in BUNDLES.items():
        parts = [
            '/* Vibe theme for EspoCRM. Generated by build.py from src/, do not edit. */\n',
            f'@import url("{ESPO_CSS}{base}");\n',
            read('fonts.css'),
            read(tokens),
            read('espo-mapping.css'),
        ]

        if with_components:
            parts.append(read('components.css'))
        else:
            parts.append(IFRAME_RULES)

        if theme_name:
            # EspoCRM compares this with the selected theme name to detect a loaded stylesheet.
            parts.append(f'body {{\n    --theme-name: {theme_name} !important;\n}}\n')

        (CSS_OUT / out_name).write_text('\n'.join(parts), encoding='utf-8')
        print(f'built {CSS_OUT.relative_to(ROOT) / out_name}')


def pack() -> None:
    manifest = json.loads((EXT / 'manifest.json').read_text(encoding='utf-8'))
    DIST.mkdir(exist_ok=True)
    target = DIST / f"vibe-theme-{manifest['version']}.zip"

    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(EXT.rglob('*')):
            if path.is_file():
                zf.write(path, path.relative_to(EXT).as_posix())

    print(f'packed {target.relative_to(ROOT)}')


if __name__ == '__main__':
    build_css()
    pack()
